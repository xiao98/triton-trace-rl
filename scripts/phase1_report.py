"""Aggregate raw Phase 1 records into metrics, cost and wall-time tables.

Reads the JSON records written by `scripts/phase1_eval.py`, writes `<out>.json` and
`<out>.md`. Every number in a report comes from here (red line 6); nothing is typed by hand.

A "sample" for the KernelBench metrics is one problem's best submission within the first
k submissions of an arm (k = 1..budget), so `best_of_n @ k=1` is plain single-shot.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "environments" / "triton_kernel_env"))

from triton_kernel_env.reward import kernelbench_metrics  # noqa: E402

# USD per million tokens: input, output, cache read, cache write. Source: Anthropic price
# list as cached in the claude-api reference on 2026-11-03. Unlisted models get no cost.
PRICES = {
    "claude-opus-5-5": (4.00, 20.00, 0.20, 5.00),
    "claude-sonnet-5-5": (2.00, 10.00, 0.10, 2.50),
}
METRICS = ["compile_rate", "correct_rate", "fast_1", "fast_1.5", "fast_2"]


def turn_cost(turn: dict) -> float | None:
    price = PRICES.get(turn["model"])
    if price is None:
        return None
    u = turn["usage"]
    return (u["input_tokens"] * price[0] + u["output_tokens"] * price[1]
            + u["cache_read_input_tokens"] * price[2]
            + u["cache_creation_input_tokens"] * price[3]) / 1e6  # fmt: skip


def best_result(turns: list[dict]) -> dict:
    return max((t["result"] for t in turns),
               key=lambda r: (r["reward"], r.get("speedup") or 0.0))  # fmt: skip


def aggregate(records: list[dict]) -> dict:
    arms: dict[str, dict] = {}
    for arm in sorted({r["arm"] for r in records}):
        recs = [r for r in records if r["arm"] == arm]
        turns = [t for r in recs for t in r["turns"]]
        costs = [turn_cost(t) for t in turns]
        budget = max(r["budget"] for r in recs)
        arms[arm] = {
            "n_problems": len(recs),
            "budget": budget,
            "metrics_at_k": {
                str(k): kernelbench_metrics([best_result(r["turns"][:k]) for r in recs])
                for k in range(1, budget + 1)
            },
            "status_counts": _count(t["result"]["status"] for t in turns),
            "stop_reasons": _count(t["stop_reason"] for t in turns),
            "models_served": _count(t["model"] for t in turns),
            "tokens": {key: sum(t["usage"][key] for t in turns) for key in turns[0]["usage"]},
            "cost_usd": None if None in costs else sum(costs),
            "api_s": sum(t["api_s"] for t in turns),
            "eval_s": sum(t["eval_s"] for t in turns),
            "episode_wall_s": sum(r["wall_s"] for r in recs),
        }
        a = arms[arm]
        a["cost_usd_per_problem"] = None if a["cost_usd"] is None else a["cost_usd"] / len(recs)
        a["episode_wall_s_per_problem"] = a["episode_wall_s"] / len(recs)
    return {
        "arms": arms,
        "problem_ids": sorted({r["problem_id"] for r in records}),
        "splits": sorted({r["split"] for r in records}),
        "run_commits": sorted({r["commit"] for r in records}),
        "requested_models": sorted({r["requested_model"] for r in records}),
        "efforts": sorted({r["effort"] for r in records}),
    }


def _count(items) -> dict[str, int]:
    out: dict[str, int] = {}
    for x in items:
        out[str(x)] = out.get(str(x), 0) + 1
    return dict(sorted(out.items()))


def project(summary: dict, n_problems: int) -> dict:
    """Linear extrapolation of cost and sequential wall time to `n_problems` per arm."""
    out = {}
    for arm, a in summary["arms"].items():
        cost = a["cost_usd_per_problem"]
        out[arm] = {"cost_usd": None if cost is None else cost * n_problems,
                    "sequential_wall_h": a["episode_wall_s_per_problem"] * n_problems / 3600}  # fmt: skip
    return out


def to_markdown(summary: dict, projections: dict[str, dict]) -> str:
    lines = [
        f"Generated by `scripts/phase1_report.py` at commit `{summary['report_commit']}` from "
        f"runs at {', '.join(f'`{c[:7]}`' for c in summary['run_commits'])}. "
        f"Split: {', '.join(summary['splits'])}; {len(summary['problem_ids'])} problems; "
        f"model {', '.join(summary['requested_models'])}, effort {', '.join(summary['efforts'])}.",
        "",
        "| arm | k | n | " + " | ".join(METRICS) + " |",
        "| --- | --- | --- | " + " | ".join("---" for _ in METRICS) + " |",
    ]
    for arm, a in summary["arms"].items():
        for k, m in a["metrics_at_k"].items():
            lines.append(f"| {arm} | {k} | {m['n']} | " + " | ".join(f"{m[x]:.3f}" for x in METRICS) + " |")
    lines += ["", "| arm | cost USD | USD / problem | input tok | output tok | cache read tok | "
              "API s | eval s | wall s / problem |", "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]  # fmt: skip
    for arm, a in summary["arms"].items():
        usd = lambda v: "n/a" if v is None else f"{v:.2f}"  # noqa: E731
        t = a["tokens"]
        lines.append(
            f"| {arm} | {usd(a['cost_usd'])} | {usd(a['cost_usd_per_problem'])} | "
            f"{t['input_tokens']} | {t['output_tokens']} | {t['cache_read_input_tokens']} | "
            f"{a['api_s']:.0f} | {a['eval_s']:.0f} | {a['episode_wall_s_per_problem']:.0f} |"
        )
    for label, proj in projections.items():
        lines += ["", f"Linear projection to {label} (wall time if run one episode at a time):", "",
                  "| arm | cost USD | sequential wall h |", "| --- | --- | --- |"]  # fmt: skip
        for arm, p in proj.items():
            cost = "n/a" if p["cost_usd"] is None else f"{p['cost_usd']:.2f}"
            lines.append(f"| {arm} | {cost} | {p['sequential_wall_h']:.1f} |")
    lines += ["", "Status of every submission: " + "; ".join(
        f"{arm}: {a['status_counts']}" for arm, a in summary["arms"].items())]  # fmt: skip
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--runs", required=True, type=Path, help="directory written by phase1_eval.py")
    ap.add_argument("--out", required=True, type=Path, help="output path without extension")
    ap.add_argument("--project", nargs="*", type=int, default=[],
                    help="problem counts to extrapolate cost / time to")  # fmt: skip
    args = ap.parse_args()

    records = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(args.runs.glob("*/*.json"))]
    if not records:
        sys.exit(f"no records under {args.runs}")
    summary = aggregate(records)
    summary["report_commit"] = subprocess.run(
        ["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True
    ).stdout.strip() or "unknown"  # fmt: skip
    projections = {f"{n} problems": project(summary, n) for n in args.project}
    summary["projections"] = projections
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.with_suffix(".json").write_text(json.dumps(summary, indent=1), encoding="utf-8")
    md = to_markdown(summary, projections)
    args.out.with_suffix(".md").write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
